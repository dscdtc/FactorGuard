def _is_trading_day(date):
    """判断单个日期是否为交易日（周一至周五 且 非节假日）"""
    if isinstance(date, str):
        date = pd.Timestamp(date)
    # 周一=0, 周日=6
    if date.dayofweek >= 5:
        return False
    date_str = date.strftime("%Y-%m-%d")
    if date_str in _CHINA_HOLIDAYS:
        return False
    return True


def get_trading_days(start_date, end_date):
    """
    返回指定日期范围内的交易日列表。

    Parameters
    ----------
    start_date : str or datetime-like
        起始日期（含）
    end_date : str or datetime-like
        结束日期（含）

    Returns
    -------
    list of str
        交易日日期字符串列表，格式 "YYYY-MM-DD"
    """
    start = pd.Timestamp(start_date)
    end = pd.Timestamp(end_date)

    try:
        calendar = pd.offsets.CustomBusinessDay(
            weekmask="Mon Tue Wed Thu Fri",
            holidays=list(_CHINA_HOLIDAYS),
        )
        dates = pd.date_range(start=start, end=end, freq=calendar)
    except Exception:
        dates = pd.date_range(start=start, end=end, freq="B")
        dates = [d for d in dates if d.strftime("%Y-%m-%d") not in _CHINA_HOLIDAYS]

    return [d.strftime("%Y-%m-%d") for d in dates]


def next_trading_day(date, n=1):
    """
    返回 date 之后第 n 个交易日。

    Parameters
    ----------
    date : str or datetime-like
        基准日期
    n : int, default 1
        偏移量，正数表示向后

    Returns
    -------
    str
        交易日日期字符串 "YYYY-MM-DD"
    """
    base = pd.Timestamp(date)
    current = base
    count = 0
    for _ in range(365):
        current = current + pd.Timedelta(days=1)
        if _is_trading_day(current):
            count += 1
            if count >= n:
                return current.strftime("%Y-%m-%d")
    raise ValueError(f"无法在 {date} 之后找到第 {n} 个交易日")


def prev_trading_day(date, n=1):
    """
    返回 date 之前第 n 个交易日。

    Parameters
    ----------
    date : str or datetime-like
        基准日期
    n : int, default 1
        偏移量，正数表示向前

    Returns
    -------
    str
        交易日日期字符串 "YYYY-MM-DD"
    """
    base = pd.Timestamp(date)
    current = base
    count = 0
    for _ in range(365):
        current = current - pd.Timedelta(days=1)
        if _is_trading_day(current):
            count += 1
            if count >= n:
                return current.strftime("%Y-%m-%d")
    raise ValueError(f"无法在 {date} 之前找到第 {n} 个交易日")


def trading_days_between(start, end):
    """
    返回两个日期之间的交易日数量（含起始和结束日期）。

    Parameters
    ----------
    start : str or datetime-like
        起始日期
    end : str or datetime-like
        结束日期

    Returns
    -------
    int
        交易日数量
    """
    days = get_trading_days(start, end)
    return len(days)